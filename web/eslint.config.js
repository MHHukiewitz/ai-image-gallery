import js from "@eslint/js";
import reactHooks from "eslint-plugin-react-hooks";
import reactRefresh from "eslint-plugin-react-refresh";
import globals from "globals";
import tseslint from "typescript-eslint";
import { defineConfig, globalIgnores } from "eslint/config";

// Layering rules from AGENTS.md: a vendor SDK is imported in one place, so swapping or mocking
// it touches one file.
const SUPABASE = {
  name: "@supabase/supabase-js",
  message:
    "Only lib/supabase.ts and features/auth may import Supabase. Data goes through lib/api.ts.",
};
const SENTRY = {
  name: "@sentry/react",
  message: "Only lib/observability.tsx may import Sentry. Log or throw instead.",
};
const restrictImports = (...paths) => ({ "no-restricted-imports": ["error", { paths }] });

export default defineConfig([
  // api-types.ts is generated by `make types`.
  globalIgnores(["dist", "src/lib/api-types.ts"]),
  {
    files: ["**/*.{ts,tsx}"],
    extends: [
      js.configs.recommended,
      tseslint.configs.recommended,
      reactHooks.configs.flat.recommended,
      reactRefresh.configs.vite,
    ],
    languageOptions: {
      ecmaVersion: 2023,
      globals: globals.browser,
    },
    rules: restrictImports(SUPABASE, SENTRY),
  },
  {
    files: ["src/lib/supabase.ts", "src/features/auth/**"],
    rules: restrictImports(SENTRY),
  },
  {
    files: ["src/lib/observability.tsx"],
    rules: restrictImports(SUPABASE),
  },
]);
